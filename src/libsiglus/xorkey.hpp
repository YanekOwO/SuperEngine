inline std::string ToHex(const xorkey_t& data) {
  constexpr char hex[] = "0123456789ABCDEF";

  std::string result;
  result.reserve(data.size() * 2);

  for (uint8_t byte : data) {
    result += hex[byte >> 4];
    result += hex[byte & 0x0F];
  }

  return result;
}

